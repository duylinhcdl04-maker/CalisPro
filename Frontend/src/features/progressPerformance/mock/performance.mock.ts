// Generate realistic Heatmap Days for past 16 weeks (June to September)
export const MOCK_CONSISTENCY_HEATMAP: ConsistencyHeatmapDay[] = Array.from({ length: 112 }, (_, i) => {
  const dayIndex = i % 7;
  const weekIdx = Math.floor(i / 7);
  // realistic activity level: higher on weekdays, medium on weekends
  const isHigh = (dayIndex === 1 || dayIndex === 3 || dayIndex === 5) && Math.random() > 0.2;
  const isMed = Math.random() > 0.4;
  const level = isHigh ? 3 : isMed ? 2 : Math.random() > 0.3 ? 1 : 0;
  const workouts = level === 3 ? 180 + Math.floor(Math.random() * 60) : level === 2 ? 120 + Math.floor(Math.random() * 40) : level === 1 ? 60 + Math.floor(Math.random() * 30) : 10;
  const students = Math.floor(workouts * 0.85);

  return {
    date: `2026-0${6 + Math.floor(weekIdx / 4)}-${String((i % 28) + 1).padStart(2, "0")}`,
    dayOfWeek: dayIndex,
    weekNumber: weekIdx + 1,
    level: level as 0 | 1 | 2 | 3,
    workoutsCount: workouts,
    activeStudentsCount: students,
  };
});

